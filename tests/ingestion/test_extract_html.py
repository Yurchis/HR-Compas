from __future__ import annotations

from pathlib import Path

from hr_compass.ingestion.infrastructure.extractors.html import extract_html, html_to_markdown

INTRANET_PAGE = """<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Paid vacation - It Company intranet</title>
<style>body{font-family:sans-serif}</style>
<script>window.dataLayer=window.dataLayer||[];</script>
</head><body>
<div class="cookie-banner" id="cookie-consent">We use cookies. <button>Accept all cookies</button></div>
<header class="site-header"><a href="/">It Company</a><form><input name="q"></form></header>
<nav><a href="/">Home</a> | <a href="/hr">HR</a> | <a href="/it">IT</a></nav>
<div class="breadcrumbs"><a href="/hr">HR</a> &gt; Paid vacation</div>
<main>
<!-- generated by the CMS -->
<h1>Paid vacation</h1>
<p>Employees get&nbsp;24 calendar days a year.​</p>
<h2>How to apply</h2>
<p>Send a request in <b>BambooHR</b> at least
   two weeks in advance.</p>
<aside>Related: Sick leave</aside>
</main>
<footer>&copy; 2026 It Company. All rights reserved. | Privacy | Terms</footer>
<script>gtag('config','UA-000000');</script>
</body></html>"""


def test_keeps_the_article_and_drops_page_chrome():
    text = html_to_markdown(INTRANET_PAGE)

    assert text == (
        "# Paid vacation\n\n"
        "Employees get 24 calendar days a year.\n\n"
        "## How to apply\n\n"
        "Send a request in BambooHR at least two weeks in advance."
    )


def test_falls_back_to_body_without_main_and_drops_the_site_header():
    html = """<body><header><h1>Intranet</h1></header>
    <div id="sidebar">Quick links</div>
    <div class="content"><h2>Remote work</h2>Approved case by case.<br>Ask your team lead.</div>
    <div style="display: none">tracking pixel</div><p hidden>old text</p></body>"""

    assert html_to_markdown(html) == "## Remote work\n\nApproved case by case.\nAsk your team lead."


def test_layout_wrapper_with_a_noisy_class_is_kept_when_it_holds_the_article():
    html = '<body><div class="page with-sidebar"><article><h1>Onboarding</h1><p>Day 1.</p></article></div></body>'

    assert html_to_markdown(html) == "# Onboarding\n\nDay 1."


def test_lists_keep_markers_and_nesting():
    html = """<main><h3>Day 1</h3>
    <ol><li>Collect your laptop</li><li><p>Set up the VPN</p><ul><li>Windows</li><li>macOS</li></ul></li></ol>
    <ul><li>Meet your buddy</li></ul></main>"""

    assert html_to_markdown(html) == (
        "### Day 1\n\n"
        "1. Collect your laptop\n2. Set up the VPN\n  - Windows\n  - macOS\n\n"
        "- Meet your buddy"
    )


def test_tables_become_markdown_rows():
    html = """<main><table>
    <tr><th>Holiday</th><th>Days</th></tr>
    <tr><td>Floating | UA</td><td>5</td></tr>
    <tr><td>US</td><td>6</td></tr></table></main>"""

    assert html_to_markdown(html) == (
        "| Holiday | Days |\n| --- | --- |\n| Floating \\| UA | 5 |\n| US | 6 |"
    )


def test_page_title_is_used_when_the_article_has_no_h1():
    html = "<html><head><title>Vision and Mission</title></head><body><main><p>We build.</p></main></body></html>"

    assert html_to_markdown(html) == "# Vision and Mission\n\nWe build."


def test_reads_a_file_in_its_declared_encoding(tmp_path: Path):
    page = tmp_path / "vacation_ua.html"
    page.write_bytes(
        '<html><head><meta charset="windows-1251"></head><body><main><h1>Відпустка</h1>'
        "<p>24 календарні дні на рік.</p></main></body></html>".encode("cp1251")
    )

    assert extract_html(page) == "# Відпустка\n\n24 календарні дні на рік."
